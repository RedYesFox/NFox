#include <stdio.h>
#include <math.h>

int main(void)
{
    const double A = 1.0;
    const double B = 10.0;
    const double H = 1.0;

    printf("%3s %6s %8s\n", "i", "X", "Y");
    int i = 1;
    for (double x = A; x <= B + (H / 10.0); x += H, i++)
    {
        printf("%4d %8.4f %8.4f\n", i, x, sqrt(x));
    }
    return 0;
}
/*
 * При использовании вещественного счётчика x += H в цикле for накапливается погрешность округления. Т.к. большиснтво десятичных дробей нельзя точно представить в двоичном виде. В конце диапазона значение X может быть чуть больше B (или меньше), из-за чего цикл пропустил последнюю точку. Поправка +(H / 10.0) может гарантировать попадание в конечную точку B.
*/
